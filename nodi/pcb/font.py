def text_strokes(s, x, y, h=1.0, anchor='left', vertical=False):
    """Restituisce le polilinee (in mm) del testo. (x, y) = angolo in alto a sinistra
    (o centro in alto se anchor='center'). vertical=True ruota di 90° (lettura dal basso)."""
    sc = h / 6.0
    adv = 5.4 * sc
    width = len(s) * adv - 1.4 * sc
    if anchor == 'center':
        x0 = -width / 2
    elif anchor == 'right':
        x0 = -width
    else:
        x0 = 0
    out = []
    for k, ch in enumerate(s.upper()):
        for stroke in F.get(ch, F['*']):
            pts = []
            for (px, py) in stroke:
                lx, ly = x0 + k * adv + px * sc, py * sc
                if vertical:
                    lx, ly = ly, -lx
                pts.append((x + lx, y + ly))
            out.append(pts)
    return out, width
